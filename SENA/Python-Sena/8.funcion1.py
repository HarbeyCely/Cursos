a = float(input("Ingrese A: "))
b = float(input("Ingrese B: "))

def sumar(a,b):
    return a+b
def restar(a,b):
    return a-b
def dividir(a,b):
    return a/b
def multiplicar(a,b):
    return a*b


print("------SUMA------")
print(sumar(a,b))

print("------RESTA------")
print(restar(a,b))

print("------DIVISION------")
print(dividir(a,b))

print("------MULTIPLICACION------")
print(multiplicar(a,b))